export function missingTranslationKeys(locale) {
  const allKeys = new Set(Object.values(translations).flatMap(catalog => Object.keys(catalog)));
  return [...allKeys].filter(key => !Object.hasOwn(translations[locale] ?? {}, key)).sort();
}

export function translationPlaceholderMismatches(locale) {
  const catalog = translations[locale] ?? {};
  const placeholders = value => [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort();
  return Object.keys(translations.en)
    .filter(key => Object.hasOwn(catalog, key))
    .filter(
      key =>
        JSON.stringify(placeholders(catalog[key])) !==
        JSON.stringify(placeholders(translations.en[key])),
    )
    .sort();
}

export function formatNumber(locale, value, options = {}) {
  const number = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(number)) return null;
  const language = translations[locale] ? locale : 'en';
  return new Intl.NumberFormat(language, options).format(number);
}

export function formatCurrency(locale, value, currency) {
  try {
    return formatNumber(locale, value, { style: 'currency', currency });
  } catch {
    return null;
  }
}

export function translate(locale, key, values = {}) {
  const language = translations[locale] ? locale : 'en';
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    const value = values[name];
    return typeof value === 'number' ? formatNumber(language, value) : (value ?? '');
  });
}

export function formatDate(locale, value, options = { dateStyle: 'medium' }) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  const language = translations[locale] ? locale : 'en';
  return new Intl.DateTimeFormat(language, options).format(date);
}

export function applyTranslations(locale, root = document) {
  const language = translations[locale] ? locale : 'en';
  root.documentElement.lang = language;
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of root.querySelectorAll('[data-i18n-html]')) {
    element.innerHTML = translate(language, element.dataset.i18nHtml);
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = translate(language, element.dataset.i18nPlaceholder);
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', translate(language, element.dataset.i18nAriaLabel));
  }
  return language;
}

export function detectLocale() {
  const stored = localStorage.getItem('maia-lms:locale');
  if (translations[stored]) return stored;
  const browserLanguage = navigator.language?.toLowerCase() ?? '';
  if (browserLanguage.startsWith('pt')) return 'pt-BR';
  if (browserLanguage.startsWith('es')) return 'es';
  return 'en';
}

export function storeLocale(locale) {
  localStorage.setItem('maia-lms:locale', locale);
}

