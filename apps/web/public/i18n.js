export function translate(locale, key, values = {}) {
  const template = translations[locale]?.[key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

export function applyTranslations(locale, root = document) {
  const language = translations[locale] ? locale : 'en';
  root.documentElement.lang = language;
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = translate(language, element.dataset.i18n);
  }
  for (const element of root.querySelectorAll('[data-i18n-html]')) {
    element.innerHTML = translate(language, element.dataset.i18nHtml);
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = translate(language, element.dataset.i18nPlaceholder);
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', translate(language, element.dataset.i18nAriaLabel));
  }
  return language;
}

export function detectLocale() {
  const stored = localStorage.getItem('maia-lms:locale');
  if (translations[stored]) return stored;
  const browserLanguage = navigator.language?.toLowerCase() ?? '';
  if (browserLanguage.startsWith('pt')) return 'pt-BR';
  if (browserLanguage.startsWith('es')) return 'es';
  return 'en';
}

export function storeLocale(locale) {
  localStorage.setItem('maia-lms:locale', locale);
}

