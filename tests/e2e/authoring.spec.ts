test('incremental autosave retries a network failure without resending unchanged lessons', async ({ page }) => {
  await page.goto('/auth/login');
  await page.getByLabel('Email', { exact: true }).fill('admin@example.com');
  await page.getByLabel('Password', { exact: true }).fill('Admin-test-password-123');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('link', { name: 'Administer', exact: true }).click();
  await page.locator('[name=title]').fill('Incremental browser course');
  await page.locator('[name=slug]').fill('incremental-browser-course');
  await page.locator('[name=summary]').fill('Verify incremental saves and local network recovery.');
  await page.locator('.module-title').fill('Module');
  await page.locator('.lesson-title').fill('First');
  await page.locator('.lesson-content').fill('Unchanged first lesson');
  await page.locator('.lesson-editor > .row-controls').getByRole('button', { name: 'Duplicate', exact: true }).click();
  await page.locator('.lesson-title').nth(1).fill('Second');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.locator('#save-status')).toContainText('Draft saved');
  let fail = true;
  const patches = [];
  await page.route('**/api/v1/admin/courses/*', async route => {
    if (route.request().method() !== 'PATCH') return route.continue();
    patches.push(route.request().postDataJSON());
    if (fail) return route.abort();
    return route.continue();
  });
  await page.locator('.lesson-content').nth(1).fill('Only this lesson changed');
  await expect(page.locator('#save-status')).toContainText('Save failed');
  expect(patches[0].changes).toHaveLength(1);
  expect(patches[0].changes[0]).toMatchObject({ unit: 'lesson', module: 0, lesson: 1, value: { body: 'Only this lesson changed' } });
  expect(JSON.stringify(patches[0])).not.toContain('Unchanged first lesson');
  await expect(page.locator('.lesson-content').nth(1)).toHaveValue('Only this lesson changed');
  page.on('dialog', dialog => dialog.accept());
  await page.reload();
  await expect(page.locator('.lesson-content').nth(1)).toHaveValue('Only this lesson changed');
  fail = false;
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.locator('#save-status')).toContainText('Draft saved');
  const courses = await (await page.request.get('/api/v1/admin/courses')).json();
  const course = courses.find(c => c.slug === 'incremental-browser-course');
  const saved = await (await page.request.get(`/api/v1/admin/courses/${course.id}`)).json();
  expect(saved.modules[0].lessons.map(l => l.body)).toEqual(['Unchanged first lesson', 'Only this lesson changed']);
});

